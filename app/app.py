def run_and_show(argv: list[str], label: str) -> tuple[int, str]:
    """Run a script, streaming its output into an expandable log."""
    st.code(h.display_command(argv), language="bash")
    box = st.status(label, expanded=True)
    log = box.empty()
    lines: list[str] = []

    def on_line(line: str) -> None:
        lines.append(line.rstrip())
        log.code("\n".join(lines[-25:]), language="text")

    code, output = h.stream(argv, on_line)
    box.update(label=f"{label}: {'done' if code == 0 else 'failed'}", state="complete" if code == 0 else "error",
               expanded=code != 0)
    return code, output


def embed_report(path: Path, height: int = 1400) -> None:
    if not path.exists():
        st.warning(f"Report not found: {path}")
        return
    st.caption(f"Report file: `{path}` (open it directly in a browser for full screen)")
    # Reports are generated by this repo's own code (trusted), never from uploads.
    st.iframe(path, height=height)


def source_picker(key: str) -> Path | None:
    sources = h.data_sources()
    if not sources:
        st.error("No market data yet. Download it once: `.venv/bin/python scripts/download_binance_history.py`, "
                 "or import files on the Data import page.")
        return None
    label = st.selectbox("Data source", list(sources), key=key)
    return sources[label]


def period_picker(key: str, allow_custom: bool = True) -> dict:
    splits = load_splits()
    options = ["train", "validation", "test (holdout)"] + (["custom range"] if allow_custom else [])
    labels = {"train": f"train ({splits['train'].start:%Y-%m-%d} → {splits['train'].end:%Y-%m-%d})",
              "validation": f"validation ({splits['validation'].start:%Y-%m-%d} → {splits['validation'].end:%Y-%m-%d})",
              "test (holdout)": f"test / holdout (from {splits['test'].start:%Y-%m-%d}) — already used once",
              "custom range": "custom date range"}
    choice = st.radio("Period", options, index=1, format_func=labels.get, key=f"{key}_split", horizontal=False)
    out = {"split": {"test (holdout)": "test", "custom range": "custom"}.get(choice, choice), "use_holdout": False}
    if out["split"] == "custom":
        c1, c2 = st.columns(2)
        out["start"] = c1.date_input("From (UTC)", date(2025, 3, 1), key=f"{key}_start")
        out["end"] = c2.date_input("To (exclusive)", date(2025, 5, 1), key=f"{key}_end")
        if pd.Timestamp(out["end"], tz="UTC") > splits["test"].start:
            out["use_holdout"] = st.checkbox("This range reaches into the holdout — I understand", key=f"{key}_ho")
    if out["split"] == "test":
        st.warning("The holdout was already used for the final evaluation. Looking again is fine, "
                   "but don't change the strategy based on what you see here.")
        out["use_holdout"] = st.checkbox("I understand — use the holdout", key=f"{key}_ho")
    return out


